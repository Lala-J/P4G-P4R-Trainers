#!/usr/bin/env python3
"""Turn mined rank events (cache/links.json, from mine_links.py) into src/dll/Data/LinkEffects.inc.

Only effects that are safe to replay are kept: unconditional calls with constant arguments, to
functions whose meaning is known. Anything inside a branch (a dialogue choice) is left to the
real hangout. The output is numbers only (link ids, ranks, flags, quest ids).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "dll", "Data", "LinkEffects.inc")

KINDS = {  # library name -> (enum, argc kept)
    "BIT_ON": ("BitOn", 1),
    "BIT_OFF": ("BitOff", 1),
    "LEARN_SL_SKILL": ("LearnSkill", 2),
    "ACCEPT_QUEST": ("AcceptQuest", 1),
    "COMPLETE_QUEST": ("CompleteQuest", 1),
    "ADD_YEN": ("AddYen", 1),
}


ROMANCE_FLAGS = {2383, 2384, 2385, 2386, 2387, 2388, 2389, 2390, 2621}


def main():
    events = json.load(open(os.path.join(HERE, "cache", "links.json")))
    rows, seen, ranks = [], set(), set()
    for e in events:
        link, rank = e["link"], e["rank"]
        if link is None or rank is None:
            continue
        ranks.add((link, rank))
        for x in e["effects"]:
            k = KINDS.get(x["call"])
            if not k or x["conditional"] or any(a is None for a in x["args"][:k[1]]):
                continue
            # Only the procedure that shows the rank-up card is the unconditional path; dialogue
            # choices live in their own procedures (e.g. "rise_friend").
            if x["proc"] != e["proc"]:
                continue
            # Romance state is never replayed: it belongs to the player's choice in the scene.
            if k[0] in ("BitOn", "BitOff") and x["args"][0] in ROMANCE_FLAGS:
                continue
            a = x["args"] + [0, 0]
            key = (link, rank, k[0], a[0], a[1] if k[1] > 1 else 0)
            if key in seen:
                continue
            seen.add(key)
            rows.append(key)
    rows.sort()
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("// Generated by tools/datamine/gen_link_effects.py from the game's own rank-event\n")
        f.write("// scripts. Unconditional, constant-argument effects only. Do not edit by hand.\n")
        f.write("// {link, rank, kind, a, b}\n")
        for r in rows:
            f.write(f"{{{r[0]}, {r[1]}, LinkFx::{r[2]}, {r[3]}, {r[4]}}},\n")
    with open(OUT.replace("LinkEffects.inc", "LinkRanksKnown.inc"), "w", encoding="utf-8",
              newline="\r\n") as f:
        f.write("// Generated: (link, rank) pairs whose rank-up event script was identified.\n")
        for link, rank in sorted(ranks):
            f.write(f"{{{link}, {rank}}},\n")
    print(f"{len(rows)} effects over {len(ranks)} identified rank events -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
