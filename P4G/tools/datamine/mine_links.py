#!/usr/bin/env python3
"""Mine every social link rank event: which event script raises which link to which rank, and
what else that script does (flags, items, quests, counters, skills, Persona changes).

    python mine_links.py            # writes cache/links.json and ../../docs/data/link_events.md

Facts only (ids, flags, ranks); no script text is written. Branch-dependent effects (inside an
IF, or in a choice procedure) are marked so the trainer never replays them blindly.
"""
import json
import os
import re
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from bf import Script, fname  # noqa: E402
from cpk import open_cpk  # noqa: E402

VISUAL = 0x302C
# Calls that are presentation only (camera, messages, models, sound, waits...).
NOISE = re.compile(r"MSG|SEL|FADE|WAIT|SYNC|CAMERA|CAM_|ANIM|SND|BGM|SE_|SOUND|MDL|MODEL|NPC|PC_|"
                   r"EXPRESSION|EFFECT|FLD_FUNCTION|EVT_FUNCTION_00(0[0-9A-F]|1[0-3])|PUT|"
                   r"SCREEN|TEXTURE|PAD|RND|CHK|GET_|LOOK|MOVE|POS|ROT|SPAWN|SET_SCRIPT", re.I)


def conditional_ranges(s):
    """Instruction ranges guarded by IF (forward branches): [(start, end)]."""
    label_ip = [ip for _, ip in s.labels]
    out = []
    for ip, op, v in s.instructions():
        if op == "IF" and 0 <= v < len(label_ip):
            tgt = label_ip[v]
            if tgt > ip:
                out.append((ip, tgt))
    return out


def mine():
    c = open_cpk("data_e.cpk")
    files = [n for n in c.names() if re.search(r"event_data/script/E\d+_\d+[A-Z]\.bf$", n)]
    events = []  # one entry per (file, proc that shows the rank-up card)
    for n in sorted(files):
        s = Script(c.read(n), n)
        calls = list(s.calls())
        ranks = [(proc, args) for proc, ip, fid, args in calls if fid == VISUAL and args[0] is not None]
        if not ranks:
            continue
        cond = conditional_ranges(s)
        effects = []
        for proc, ip, fid, args in calls:
            name = fname(fid)
            if fid == VISUAL or NOISE.search(name):
                continue
            guarded = any(a <= ip < b for a, b in cond)
            effects.append({"proc": proc, "call": name, "args": args, "conditional": guarded})
        for proc, args in ranks:
            events.append({"file": n.split("/")[-1], "proc": proc, "link": args[0], "rank": args[1],
                           "card": args[2], "effects": effects})
    return events


def write_doc(events, path):
    by_link = defaultdict(list)
    for e in events:
        by_link[e["link"]].append(e)
    lines = ["# Social link rank events (mined)", "",
             "Generated by `tools/datamine/mine_links.py` from the player's own `data_e.cpk`.",
             "Each row: the event script that shows the rank-up card for a link and rank, and the",
             "non-presentation calls it makes. `*` marks calls inside a branch (choice-dependent).", ""]
    for link in sorted(by_link):
        lines.append(f"## Link {link}")
        lines.append("")
        lines.append("| Rank | Script | Effects |")
        lines.append("|---|---|---|")
        seen = set()
        for e in sorted(by_link[link], key=lambda x: (x["rank"] if x["rank"] is not None else -1, x["file"])):
            key = (e["rank"], e["file"])
            if key in seen:
                continue
            seen.add(key)
            eff = "; ".join(f"{'*' if x['conditional'] else ''}{x['call']}("
                            f"{', '.join('?' if a is None else str(a) for a in x['args'])})"
                            for x in e["effects"]) or "—"
            lines.append(f"| {e['rank']} | {e['file']} | {eff} |")
        lines.append("")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    events = mine()
    os.makedirs(os.path.join(HERE, "cache"), exist_ok=True)
    json.dump(events, open(os.path.join(HERE, "cache", "links.json"), "w"), indent=1)
    doc = os.path.join(HERE, "..", "..", "docs", "data", "link_events.md")
    write_doc(events, doc)
    links = sorted({e["link"] for e in events})
    print(f"{len(events)} rank events over links {links}")


if __name__ == "__main__":
    main()
